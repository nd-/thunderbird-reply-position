/* Turns the report of the harness into versioned HTML fixtures, the input of the unit tests
 * of lib/layout.js.
 *
 * Every fixture carries, as a leading comment, the expected state of the composer at capture
 * time: original position and cursor. A failing test then points straight back at what
 * Thunderbird was producing, without having to reopen the report.
 */

import { readFile, writeFile, mkdir, readdir, rm } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPORT = join(ROOT, ".tmp", "report.json");
const DESTINATION = join(ROOT, "test", "fixtures");

const header = (testCase) => {
  const { selection, presence, textLength } = testCase.probe.delayed;
  const lines = [
    `Fixture generated by tools/extract-fixtures.mjs, do not edit by hand.`,
    ``,
    `Case         : ${testCase.id}`,
    `               ${testCase.comment}`,
    `Message      : ${testCase.message}`,
    `Action       : ${testCase.action}`,
    `Plain text   : ${testCase.details.isPlainText ? "yes" : "no"}`,
    `Prefs        : ${Object.entries(testCase.prefs)
      .filter(([name]) => /reply_on_top|sig_bottom|sig_on_reply|compose_html/.test(name))
      .map(([name, value]) => `${name.replace("mail.identity.id1.", "")}=${value}`)
      .join(", ")}`,
    `Selectors    : moz-cite-prefix ${presence.citePrefix}, blockquote[type=cite] ${presence.blockquoteCite}, ` +
      `moz-signature ${presence.signature}, moz-forward-container ${presence.forwardContainer}`,
    `Cursor       : ${selection.isCollapsed ? "collapsed" : "extended"}, anchor ${selection.anchorNode} @${selection.anchorOffset}` +
      (selection.isCollapsed ? "" : `, focus @${selection.focusOffset}`),
    `Body text    : ${textLength} characters`,
  ];
  return `<!--\n${lines.join("\n")}\n-->\n`;
};

const main = async () => {
  const report = JSON.parse(await readFile(REPORT, "utf8"));
  const valid = report.cases.filter((testCase) => !testCase.error && testCase.probe?.delayed);
  if (!valid.length) {
    console.error("No usable case in the report.");
    process.exit(1);
  }

  await mkdir(DESTINATION, { recursive: true });
  /* The fixtures are entirely derived from the report: whatever was not captured in the
   * last run has no business surviving in the directory. */
  for (const name of await readdir(DESTINATION)) {
    if (name.endsWith(".html")) await rm(join(DESTINATION, name));
  }

  for (const testCase of valid) {
    const path = join(DESTINATION, `${testCase.id}.html`);
    await writeFile(path, header(testCase) + testCase.probe.delayed.innerHTML, "utf8");
    console.log(`${testCase.id}.html`);
  }
  console.log(`\n${valid.length} fixtures written to ${DESTINATION}`);
};

await main();
